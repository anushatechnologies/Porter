    @Test
    void testDeliveryOtpEndpoints_ReturnOtpAndDeliveryOtpAcrossAllRouteAliases() throws Exception {
        String bookingId = "BK-OTP-TEST-001";
        Order order = new Order();
        order.setBookingId(bookingId);
        order.setUserEmail("user@example.com");
        order.setServiceName("Tata Ace");
        order.setStatus("assigned");
        order.setDeliveryOtp("7291");
        orderRepository.save(order);

        // 1. GET /api/bookings/{id}/delivery-otp
        mockMvc.perform(get("/api/bookings/" + bookingId + "/delivery-otp"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.bookingId", is(bookingId)))
                .andExpect(jsonPath("$.otp", is("7291")))
                .andExpect(jsonPath("$.deliveryOtp", is("7291")))
                .andExpect(jsonPath("$.data.otp", is("7291")))
                .andExpect(jsonPath("$.data.deliveryOtp", is("7291")));

        // 2. GET /api/orders/{id}/delivery-otp
        mockMvc.perform(get("/api/orders/" + bookingId + "/delivery-otp"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.otp", is("7291")))
                .andExpect(jsonPath("$.deliveryOtp", is("7291")));

        // 3. GET /api/bookings/{id}/otp
        mockMvc.perform(get("/api/bookings/" + bookingId + "/otp"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.otp", is("7291")))
                .andExpect(jsonPath("$.deliveryOtp", is("7291")));

        // 4. GET /api/orders/{id}/otp
        mockMvc.perform(get("/api/orders/" + bookingId + "/otp"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.otp", is("7291")))
                .andExpect(jsonPath("$.deliveryOtp", is("7291")));
    }

    @Test
    void testDeliveryOtp_AutoGeneratedIfNullWhenRequested() throws Exception {
        String bookingId = "BK-OTP-NULL-002";
        Order order = new Order();
        order.setBookingId(bookingId);
        order.setUserEmail("user@example.com");
        order.setServiceName("Tata Ace");
        order.setStatus("assigned");
        order.setDeliveryOtp(null); // No OTP initially
        orderRepository.save(order);

        // Querying delivery-otp must auto-generate, persist and return it
        mockMvc.perform(get("/api/bookings/" + bookingId + "/delivery-otp"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.otp", notNullValue()))
                .andExpect(jsonPath("$.deliveryOtp", notNullValue()));

        Order refreshed = orderRepository.findByBookingId(bookingId).orElseThrow();
        assertNotNull(refreshed.getDeliveryOtp());
        assertEquals(4, refreshed.getDeliveryOtp().length());
    }

