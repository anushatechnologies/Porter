    @Test
    void testCancellationAllowed_WhilePlacingOrderAndInTransit() throws Exception {
        String bookingId = "BK-CANCEL-TEST-001";
        Order order = new Order();
        order.setBookingId(bookingId);
        order.setUserEmail("customer@example.com");
        order.setServiceName("2 Wheeler");
        order.setStatus("searching");
        order.setDeliveryOtp("5555");
        orderRepository.save(order);

        // 1. Verify tracking exposes canCancel: true while placing order / searching
        mockMvc.perform(get("/api/bookings/" + bookingId + "/tracking"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.canCancel", is(true)))
                .andExpect(jsonPath("$.isCancellable", is(true)));

        // 2. Perform cancellation via PUT
        mockMvc.perform(put("/api/bookings/" + bookingId + "/cancel")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"reason\": \"Changed mind\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.success", is(true)))
                .andExpect(jsonPath("$.status", is("cancelled")));

        // Verify DB status
        Order cancelledOrder = orderRepository.findByBookingId(bookingId).orElseThrow();
        assertEquals("cancelled", cancelledOrder.getStatus());
    }

    @Test
    void testCancellationBlocked_WhenDriverArrivedAtDropLocation() throws Exception {
        String bookingId = "BK-CANCEL-TEST-002";
        Order order = new Order();
        order.setBookingId(bookingId);
        order.setUserEmail("customer@example.com");
        order.setServiceName("Tata Ace");
        order.setStatus("driver_reached");
        order.setDeliveryOtp("7777");
        orderRepository.save(order);

        // 1. Tracking must show canCancel: false
        mockMvc.perform(get("/api/bookings/" + bookingId + "/tracking"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.canCancel", is(false)))
                .andExpect(jsonPath("$.isCancellable", is(false)))
                .andExpect(jsonPath("$.cancellationBlockedReason", notNullValue()));

        // 2. Attempting to cancel must return 400 Bad Request
        mockMvc.perform(put("/api/bookings/" + bookingId + "/cancel")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"reason\": \"Want to cancel\"}"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.success", is(false)))
                .andExpect(jsonPath("$.error", is("CANCELLATION_WINDOW_EXPIRED")))
                .andExpect(jsonPath("$.canCancel", is(false)));
    }

    @Test
    void testCancellationBlocked_WhenDriverGpsWithin300MetersOfDrop() throws Exception {
        Driver driver = new Driver();
        driver.setName("Proximity Driver");
        driver.setEmail("prox@driver.com");
        driver.setPhone("9988776655");
        driver.setLatitude(17.4402);
        driver.setLongitude(78.3802);
        driver = driverRepository.save(driver);

        String bookingId = "BK-CANCEL-TEST-003";
        Order order = new Order();
        order.setBookingId(bookingId);
        order.setUserEmail("customer@example.com");
        order.setServiceName("Tata Ace");
        order.setStatus("in_transit");
        order.setDriverId(driver.getId().toString());
        order.setDropLat(17.4400); // Distance is ~30 meters!
        order.setDropLng(78.3800);
        orderRepository.save(order);

        // Tracking must show canCancel: false due to proximity
        mockMvc.perform(get("/api/bookings/" + bookingId + "/tracking"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.canCancel", is(false)));

        // Attempting to cancel must return 400 Bad Request
        mockMvc.perform(post("/api/bookings/" + bookingId + "/cancel")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"reason\": \"Too late cancel\"}"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.success", is(false)))
                .andExpect(jsonPath("$.error", is("CANCELLATION_WINDOW_EXPIRED")));
    }

